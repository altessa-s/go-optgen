func TestReaderExcludesTestsAndGeneratedFiles(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for name, src := range map[string]string{
		"options.go":     "package sample\ntype options struct { count int `opt:\"Count\"` }",
		"broken_test.go": "invalid",
		// Generated files are recognized by their header, not their name.
		"options_gen.go":  "// Code generated by optgen. DO NOT EDIT.\n\npackage sample\ntype settings struct { stale int `opt:\"Stale\"` }",
		"settings_gen.go": "package sample\ntype settings struct { live int `opt:\"Live\"` }",
	} {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(src), 0o600))
	}
	packages, err := (source.Reader{}).Parse(t.Context(), dir, "options", false)
	require.NoError(t, err)
	require.Len(t, packages, 1)
	require.Len(t, packages[0].Fields, 1)
	require.Equal(t, "count", packages[0].Fields[0].FieldName)

	packages, err = (source.Reader{}).Parse(t.Context(), dir, "settings", false)
	require.NoError(t, err)
	require.Len(t, packages[0].Fields, 1)
	require.Equal(t, "live", packages[0].Fields[0].FieldName, "a hand-written _gen.go file is parsed; the generated one is skipped")
}

func TestReaderResolvesTypesInsideModules(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for name, src := range map[string]string{
		"go.mod": "module sample\n\ngo 1.26\n",
		"options.go": "package sample\nimport \"io\"\ntype Port int\ntype Key struct{ A string }\n" +
			"type options struct {\n w io.Writer `opt:\"W\"`\n port Port `opt:\"Port\"`\n keys []Key `opt:\"Keys\"`\n}\n" +
			"func use() { _ = newOptions() } // not generated yet\n",
	} {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(src), 0o600))
	}
	packages, err := (source.Reader{}).Parse(t.Context(), dir, "options", false)
	require.NoError(t, err)
	require.Len(t, packages, 1)
	byName := make(map[string]model.OptField)
	for _, f := range packages[0].Fields {
		byName[f.FieldName] = f
	}
	require.True(t, byName["w"].TypeResolved)
	require.True(t, byName["w"].IsInterface, "named interfaces are recognized")
	require.True(t, byName["port"].IsNumeric)
	require.False(t, byName["port"].IsNilable)
	require.True(t, byName["keys"].ElemComparable)
}

func TestReaderFallsBackOutsideModules(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "options.go"), []byte("package sample\ntype options struct { n int `opt:\"N\"` }\n"), 0o600))
	packages, err := (source.Reader{}).Parse(t.Context(), dir, "options", false)
	require.NoError(t, err)
	require.False(t, packages[0].Fields[0].TypeResolved)
}

func TestReaderReportsParseErrorsAndCancellation(t *testing.T) {
	t.Parallel()
	for name, files := range map[string]map[string]string{
		"module":         {"go.mod": "module sample\n\ngo 1.26\n", "options.go": "package sample\ntype options struct {"},
		"outside module": {"options.go": "package sample\ntype options struct {"},
	} {
		dir := t.TempDir()
		for file, src := range files {
			require.NoError(t, os.WriteFile(filepath.Join(dir, file), []byte(src), 0o600))
		}
		_, err := (source.Reader{}).Parse(t.Context(), dir, "options", false)
		require.ErrorContains(t, err, "failed to parse directory", name)
	}

	empty := t.TempDir()
	_, err := (source.Reader{}).Parse(t.Context(), empty, "options", false)
	require.ErrorContains(t, err, "no packages found")

	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	_, err = (source.Reader{}).Parse(ctx, empty, "options", false)
	require.ErrorIs(t, err, context.Canceled)
}

func TestReaderLeavesTypeParametersUnresolved(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for name, src := range map[string]string{
		"go.mod":     "module sample\n\ngo 1.26\n",
		"options.go": "package sample\ntype options[T any] struct {\n v T `opt:\"V\"`\n c complex128 `opt:\"C\"`\n bad Missing `opt:\"Bad\"`\n}\n",
	} {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(src), 0o600))
	}
	packages, err := (source.Reader{}).Parse(t.Context(), dir, "options", false)
	require.NoError(t, err)
	byName := make(map[string]model.OptField)
	for _, f := range packages[0].Fields {
		byName[f.FieldName] = f
	}
	require.False(t, byName["v"].TypeResolved, "type parameters depend on the instantiation")
	require.False(t, byName["bad"].TypeResolved, "undefined types stay unresolved")
	require.True(t, byName["c"].TypeResolved)
	require.False(t, byName["c"].IsNumeric, "complex numbers are not ordered")
}
